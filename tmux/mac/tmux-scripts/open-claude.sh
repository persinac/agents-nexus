#!/usr/bin/env bash
# Launch claude with recent checkpoint context injected as the opening message.
# Reads checkpoint notes from $CHECKPOINT_DIR (or legacy $NOTES_DIR) for the current repo (past 3 days).
# Also registers this agent in the shared registry (~/.tmux/registry/) and
# injects agent communication tool instructions into the startup prompt.
# Falls back to plain `claude` if no notes found.
#
# Cross-platform (mac + Linux): the few OS-specific bits are guarded inline ($OSTYPE / a
# `[ -d ]` probe / BSD-or-GNU `date`+`stat` fallbacks), so this is the ONE shared copy —
# there is no per-OS override. env.defaults.sh (committed) then env.sh (per-machine,
# generated) are sourced first and supply machine paths + routing.

# Fleet install root. Self-default so this resolves for a spawned agent whose env
# was stripped (herdr pane); env.defaults.sh + substrate re-export the canonical value.
NEXUS_TMUX_DIR="${NEXUS_TMUX_DIR:-$HOME/.tmux}"
# Portable defaults FIRST (committed; works with no install.sh run — the degrade path),
# then the per-machine env.sh ON TOP (generated by install.sh; may be absent).
[ -f "$NEXUS_TMUX_DIR/env.defaults.sh" ] && source "$NEXUS_TMUX_DIR/env.defaults.sh"
[ -f "$NEXUS_TMUX_DIR/env.sh" ] && source "$NEXUS_TMUX_DIR/env.sh"

# Fleet env for agents that don't inherit a login shell (herdr panes; any spawn with a
# stripped env). Load the repo .env — DATABASE_URL (agent-memory MCP), bus config,
# tokens — so the agent AND its MCP servers get it. Read-and-export KEY=value (no shell
# eval of values; .env is written for node's loader), filling gaps only so we never
# override an already-set var (matches the slack-bridge .env loader semantics).
# env.sh normally sets AGENTS_NEXUS_DIR; the default is only a last resort and differs by
# OS layout (mac: ~/repos, Linux personal box: ~/repos).
case "$OSTYPE" in
  darwin*) _NEXUS_DEFAULT="$HOME/repos/agents-nexus" ;;
  *)       _NEXUS_DEFAULT="$HOME/repos/agents-nexus" ;;
esac
_ENV_FILE="${AGENTS_NEXUS_DIR:-$_NEXUS_DEFAULT}/.env"
if [ -f "$_ENV_FILE" ]; then
  while IFS='=' read -r _k _v; do
    case "$_k" in ''|\#*) continue ;; esac
    [ -z "${!_k:-}" ] && export "$_k=$_v"
  done < "$_ENV_FILE"
fi

# fnm (Linux) puts node/claude under a default-alias bin that a stripped popup PATH misses,
# so `exec claude` below would be "not found". Prepend it when present (self-guarded — the
# dir doesn't exist on mac/homebrew boxes, so this is a no-op there).
_FNM_BIN="$HOME/.local/share/fnm/aliases/default/bin"
[ -d "$_FNM_BIN" ] && case ":$PATH:" in *":$_FNM_BIN:"*) ;; *) export PATH="$_FNM_BIN:$PATH" ;; esac

# Claude Code self-updates in TWO stages: npm unpacks package.json + install.cjs, then
# install.cjs downloads the ~330MB platform binary into bin/claude.exe. Between those two
# steps the `claude` symlink sitting on PATH DANGLES — `command -v claude` prints nothing
# and exits 1 (indistinguishable from "not installed"), so the `exec claude` at the bottom
# of this script dies instantly and takes the pane with it BEFORE it can render anything.
# The user sees a keybind that "does nothing"; the error goes nowhere. Measured window:
# ~3m20s on 2026-08-19 (v2.1.235). An already-running agent survives it by holding the old
# inode open, which makes the fleet look half-broken rather than mid-update.
#
# The install self-heals, so wait it out rather than failing. Structural check only (no
# `claude --version` probe) — this runs on EVERY spawn and the happy path must stay free.
_claude_ready() {
  _cr_path="$(command -v claude 2>/dev/null)" || return 1
  [ -n "$_cr_path" ] && [ -x "$_cr_path" ]
}
if ! _claude_ready; then
  _cw_waited=0
  _cw_limit="${CLAUDE_WAIT_SECS:-300}"
  echo "open-claude: 'claude' not resolvable yet — likely a Claude Code self-update in flight; waiting up to ${_cw_limit}s" >&2
  while ! _claude_ready && [ "$_cw_waited" -lt "$_cw_limit" ]; do
    sleep 2
    _cw_waited=$((_cw_waited + 2))
    [ $((_cw_waited % 30)) -eq 0 ] && echo "open-claude: still waiting for 'claude' (${_cw_waited}s/${_cw_limit}s)" >&2
  done
  if _claude_ready; then
    echo "open-claude: 'claude' resolved after ${_cw_waited}s — continuing" >&2
  else
    # Hold the pane open. Exiting here would reproduce the exact silent-vanish this guards.
    echo "open-claude: FATAL — 'claude' still not executable after ${_cw_limit}s; not launching." >&2
    echo "  PATH=$PATH" >&2
    echo "  Check:  ls -la \"$_FNM_BIN/claude\"" >&2
    echo "  A dangling symlink there means an update died midway. Repair with:" >&2
    echo "    npm i -g @anthropic-ai/claude-code" >&2
    if [ -t 0 ]; then
      echo "  Press Enter to close this pane." >&2
      read -r _cw_ack || true
    else
      sleep 60
    fi
    exit 127
  fi
fi

# ANTHROPIC_BASE_URL is decided by the env layer (env.defaults.sh probes the local
# LiteLLM gateway and sets it only when reachable; env.sh may override). Do NOT force
# a localhost fallback here — on a box with no gateway that pointed every agent at a
# dead URL. Unset = talk to Anthropic directly, which is the correct degrade.

# Resolve checkpoint source — prefer CHECKPOINT_DIR (matches the writer skill);
# fall back to NOTES_DIR for back-compat with older env.sh installs.
CHECKPOINT_SRC="${CHECKPOINT_DIR:-${NOTES_DIR:-$HOME/vault/Checkpoints}}"
REPO_PATH="${PWD}"

# project_slug: the REPO's name, not the checkout directory's.
#
# These are the same for an ordinary clone and differ for a git worktree, whose
# directory is named <parent>_<repo>--<branch> — so a worktree agent registered
# as "flashback-fleet_management-dashboard--business-hours" instead of
# "management-dashboard".
#
# That is not just unpleasant to type on the bus. project_slug ALSO keys the
# agent-memory project, the checkpoint filenames and the prompt cache (see the
# uses below), so a worktree-spawned agent silently came up with none of its
# project's memory and wrote its checkpoints to a namespace nothing else reads.
# The bus name was the visible symptom; the lost continuity was the actual bug.
#
# git-common-dir resolves to the MAIN checkout's .git from inside a worktree and
# to the repo's own .git otherwise, so this returns exactly what basename used to
# for a normal clone — verified against both before changing it.
_slug_from_git() {
    local common main
    common=$(git -C "$REPO_PATH" rev-parse --path-format=absolute --git-common-dir 2>/dev/null) || return 1
    [ -n "$common" ] || return 1
    main=$(dirname "$common")
    [ -d "$main" ] || return 1
    basename "$main"
}

# A name already claimed by a LIVE agent must not be handed out twice: the bus
# resolves by name and takes the first match, so a duplicate would silently
# deliver another agent's messages here. Two worktrees of one repo hit this, and
# it is the case the long directory name was accidentally protecting against —
# so fall back to the directory name rather than collide.
_slug_is_taken() {
    local want="$1" f
    for f in "$HOME/.tmux/registry"/*; do
        [ -f "$f" ] || continue
        [ "$(basename "$f")" = "${TMUX_PANE:-${HERDR_PANE_ID:-}}" ] && continue
        [ "$(grep -m1 '^NAME=' "$f" 2>/dev/null | cut -d= -f2)" = "$want" ] && return 0
    done
    return 1
}

if [ -n "${PROJECT_SLUG:-}" ]; then
    project_slug="$PROJECT_SLUG"                      # explicit override always wins
else
    project_slug="$(basename "$REPO_PATH")"
    _git_slug="$(_slug_from_git || true)"
    if [ -n "$_git_slug" ] && [ "$_git_slug" != "$project_slug" ] && ! _slug_is_taken "$_git_slug"; then
        project_slug="$_git_slug"
    fi
fi

# ── Agent-memory Python (venv used by the MCP server) ──────────────────────
_AGENT_MEM_VENV="${AGENTS_NEXUS_DIR:-$HOME/repos/agents-nexus}/mnemon/.venv"
if [ -x "$_AGENT_MEM_VENV/bin/python3" ]; then
  MEMORY_PYTHON="$_AGENT_MEM_VENV/bin/python3"
elif [ -x "$_AGENT_MEM_VENV/Scripts/python3.exe" ]; then
  MEMORY_PYTHON="$_AGENT_MEM_VENV/Scripts/python3.exe"
else
  MEMORY_PYTHON="python3"
fi

# ── Register this agent in the shared registry ─────────────────────────────
# Files are keyed by pane ID (stable — unaffected by renumber-windows).
# tmux sets TMUX_PANE; herdr sets HERDR_PANE_ID — fold herdr's in so the agent
# registers (registry + name) in both substrates.
TMUX_PANE="${TMUX_PANE:-${HERDR_PANE_ID:-}}"
MY_PANE_ID="$TMUX_PANE"
MY_NAME="$project_slug"
# Workspace (bucket) label: set at spawn via NEXUS_WORKSPACE; else derive from the pane
# (herdr). Empty for flat/default agents, which resolve as unscoped (thin) names.
MY_WORKSPACE="${NEXUS_WORKSPACE:-}"
[ -z "$MY_WORKSPACE" ] && MY_WORKSPACE="$("$NEXUS_TMUX_DIR/substrate.sh" workspace-of "$MY_PANE_ID" 2>/dev/null || true)"

# This host's presence/FQDN label. SINGLE source = SLACK_PRESENCE_HOST — the SAME var the bridge's
# SELF_HOST (index.js) and agent-resolve.sh's nx_self_host() read — falling back to the short
# hostname. Injected into base context (Agent Communication, below) so an agent can tell whether a
# bus peer is same-host or remote: FQDN-style peer names are `<host>/…/<name>`, so a peer prefixed
# "$MY_HOST/" is on THIS box — hand files off by writing into its repo tree (no S3/user-drop detour).
MY_HOST="${SLACK_PRESENCE_HOST:-$(hostname -s 2>/dev/null || hostname 2>/dev/null || echo unknown)}"

# A2A sender identity — export the FULL FQDN component (workspace/name) so agent-send.sh
# stamps a `host/workspace/name` `from` WITHOUT depending on a live registry lookup. A bare
# name is ambiguous when the same name exists in >1 workspace (e.g. several `general`s), which
# makes a recipient misread a message as a self-loopback. The bridge adds the host (SELF_HOST).
# Honors an AGENT_FROM the launcher already set; empty workspace → bare name (flat/unscoped).
if [ -z "${AGENT_FROM:-}" ]; then
  if [ -n "$MY_WORKSPACE" ]; then export AGENT_FROM="$MY_WORKSPACE/$MY_NAME"; else export AGENT_FROM="$MY_NAME"; fi
fi

# Lock the window name so tmux doesn't override it with the process name
"$NEXUS_TMUX_DIR/substrate.sh" rename "$MY_PANE_ID" "$MY_NAME" 2>/dev/null

# The command post (overseer/orchestrator) is where you drive from — never an
# agent to reap. Tag it so the idle reaper protects it even if later renamed.
case "$MY_NAME" in
  overseer|orchestrator) "$NEXUS_TMUX_DIR/substrate.sh" tag-orchestrator "$MY_PANE_ID" 2>/dev/null ;;
esac

# ── Direct-auth carve-out: strip the gateway env for command-post panes ─────
# See NEXUS_DIRECT_AUTH_AGENTS in env.defaults.sh for the full why. Short form:
# Remote Control (/remote-control, /rc) refuses to register when an API key or
# auth token resolves, so a gateway-routed pane cannot be driven from a phone.
#
# Matched against BOTH the agent name and the workspace label, because a command
# post is usually named for its launch dir (e.g. `general`) and is identifiable
# only by NEXUS_WORKSPACE — matching on name alone would miss it, which is the
# same blind spot the tag-orchestrator case above still has.
#
# This must run AFTER env.sh (which re-forces ANTHROPIC_BASE_URL with a `:-`
# default) and BEFORE the /sess append below — hence here, not in the env layer.
# `unset` rather than reassignment is load-bearing: the gate tests for
# source==="none", and an empty-but-present var still resolves to a source.
_direct_auth=0
# shellcheck disable=SC2086  # deliberate word-split: the knob is a space-separated list
for _da in ${NEXUS_DIRECT_AUTH_AGENTS:-}; do
  if [ "$_da" = "$MY_NAME" ] || { [ -n "$MY_WORKSPACE" ] && [ "$_da" = "$MY_WORKSPACE" ]; }; then
    _direct_auth=1
    break
  fi
done
if [ "$_direct_auth" = "1" ]; then
  unset ANTHROPIC_BASE_URL ANTHROPIC_API_KEY ANTHROPIC_AUTH_TOKEN
  echo "open-claude: direct-auth pane (${MY_NAME}/${MY_WORKSPACE:-flat}) — gateway env stripped; /remote-control available, NO Langfuse trace for this session" >&2
fi
unset _da _direct_auth

# ── Tag LLM traffic so Langfuse names the trace after this window ───────────
# The proxy reads a `sess/<name>/` path prefix and uses it as the trace name +
# session id; without it every agent shows up as "claude-code". Slugify to a
# URL-path-safe segment (the proxy splits the prefix on the first "/").
if [ -n "${ANTHROPIC_BASE_URL:-}" ] && [ -n "$MY_NAME" ]; then
  _sess_slug=$(printf '%s' "$MY_NAME" | tr -c 'A-Za-z0-9._-' '-')
  export ANTHROPIC_BASE_URL="${ANTHROPIC_BASE_URL%/}/sess/${_sess_slug}"
fi

# Gate on the PANE only. `register` is keyed by pane and takes no slot, so the old
# `&& [ -n "$MY_SLOT" ]` gated registration on a window-index query (substrate
# pane-field) that RACES on herdr: at spawn time the daemon doesn't yet know a
# freshly-created pane, so pane-field returned empty → registration was silently
# skipped, leaving bridge-spawned agents unregistered (invisible to /agents, their
# permission prompts un-routed to Slack → wedged at the first prompt). MY_PANE_ID
# comes from HERDR_PANE_ID in the env (no daemon query), so it's reliably set.
if [ -n "$MY_PANE_ID" ]; then
  # Route through the shared `substrate register` verb (the one writer of the registry
  # format), so picker launches and seam-spawned agents register identically.
  "$NEXUS_TMUX_DIR/substrate.sh" register "$MY_PANE_ID" "$MY_NAME" "$REPO_PATH" "$MY_WORKSPACE"
  # Log session_start to memory buffer (best-effort — absent on a fleet-less install).
  [ -x "$NEXUS_TMUX_DIR/memory-hook.py" ] && "$NEXUS_TMUX_DIR/memory-hook.py" session_start "$MY_PANE_ID" "$REPO_PATH" &
fi

# ── Recent checkpoint notes ────────────────────────────────────────────────
# Gated by NEXUS_INJECT_CHECKPOINTS (0 = omit); lookback by NEXUS_CHECKPOINT_DAYS;
# total size capped by NEXUS_CHECKPOINT_MAX_KB (0 = unlimited). See env.defaults.sh.
context=""
if [ "${NEXUS_INJECT_CHECKPOINTS:-1}" = "1" ] && [ "${NEXUS_CONTEXT_MODE:-full}" != "pointer" ]; then
  _ckpt_days="${NEXUS_CHECKPOINT_DAYS:-3}"
  # BSD date (Mac): -v-Nd; GNU date (Linux): -d 'N days ago'
  cutoff=$(date -v-"${_ckpt_days}"d +%Y-%m-%d 2>/dev/null || date -d "${_ckpt_days} days ago" +%Y-%m-%d)
  # Collect matching checkpoint files within the window, sorted oldest→newest
  while IFS= read -r f; do
    date_part=$(basename "$f" | cut -c1-10)
    if [[ "$date_part" > "$cutoff" || "$date_part" = "$cutoff" ]]; then
      context+="$(cat "$f")"$'\n\n'
    fi
  done < <(ls -1 "$CHECKPOINT_SRC"/*-${project_slug}-checkpoint.md 2>/dev/null | sort)
  # Optional size cap — keep the NEWEST bytes (files are oldest→newest, so the
  # freshest checkpoint is at the tail and matters most). 0 disables the cap.
  _ckpt_max_kb="${NEXUS_CHECKPOINT_MAX_KB:-0}"
  if [ "$_ckpt_max_kb" -gt 0 ] 2>/dev/null; then
    _ckpt_max_bytes=$(( _ckpt_max_kb * 1024 ))
    if [ "${#context}" -gt "$_ckpt_max_bytes" ]; then
      context="[older checkpoint context trimmed to ${_ckpt_max_kb}KB via NEXUS_CHECKPOINT_MAX_KB]"$'\n\n'"${context: -$_ckpt_max_bytes}"
    fi
  fi
fi

# ── Auto-cache recovery (previous session context) ───────────────────────
CACHE_FILE="$NEXUS_TMUX_DIR/cache/${project_slug}.md"
cache_section=""
if [ "${NEXUS_INJECT_CACHE:-1}" = "1" ] && [ -f "$CACHE_FILE" ]; then
  # Capture each stat arm into its own assignment. A `||` chain INSIDE $( ) keeps the
  # stdout of the FAILING arm too: on Linux `stat -f` is --file-system, so it prints a
  # whole filesystem block, exits non-zero, and the GNU arm's epoch gets appended to it.
  # The result is a fatal arithmetic syntax error that exits the shell at this line.
  cache_mtime=$(stat -c %Y "$CACHE_FILE" 2>/dev/null) || cache_mtime=$(stat -f %m "$CACHE_FILE" 2>/dev/null) || cache_mtime=0
  cache_age=$(( $(date +%s) - ${cache_mtime:-0} ))
  if [ "$cache_age" -lt 86400 ]; then
    cache_section=$(cat "$CACHE_FILE")
    mv "$CACHE_FILE" "${CACHE_FILE%.md}.used" 2>/dev/null
  else
    rm -f "$CACHE_FILE"
  fi
fi

# ── Agent communication tools ─────────────────────────────────────────────
REGISTRY_SCRIPT="$NEXUS_TMUX_DIR/agent-registry.sh"
SEND_SCRIPT="$NEXUS_TMUX_DIR/agent-send.sh"
# Is the agent bus live? Probe the local bridge's health (cheap, <1s) so we document
# the bus as the DEFAULT transport only when it can actually deliver. `--via-bus`
# force-routes through the bridge regardless of the agent's NEXUS_BUS_ENABLED, so the
# bridge's own bus state — not an env var — is the right signal. No bridge / bus off ->
# fall back to the local-only guidance.
bus_on=0
if command -v curl >/dev/null 2>&1; then
  case "$(curl -s --max-time 1 "http://127.0.0.1:${NEXUS_BUS_PORT:-${SLACK_BRIDGE_PORT:-8788}}/health" 2>/dev/null)" in
    *'"bus":true'*) bus_on=1 ;;
  esac
fi
registry_section=""
if [ "${NEXUS_INJECT_REGISTRY:-1}" = "1" ] && [ "${NEXUS_CONTEXT_MODE:-full}" != "pointer" ] && [ -x "$REGISTRY_SCRIPT" ]; then
  peers_output=$("$REGISTRY_SCRIPT" peers --exclude "$MY_PANE_ID" 2>/dev/null || true)
  if [ "$bus_on" = "1" ]; then
    comms_body="**To message another agent, DEFAULT to the NATS agent bus.** Post once and the orchestrator delivers it idle-gated, buffered, and durable (JetStream holds it if the recipient's bridge is down), across hosts:
  - \`$SEND_SCRIPT <host>/<workspace>/<name> <message>\` — deliver to that agent when it next goes idle

**Address agents by FQDN.** The registry is a NATS JetStream KV bucket keyed \`<host>.<workspace>.<name>\`; you type the same identity slash-separated. You are \`${MY_HOST}/<your-workspace>/${MY_NAME}\`. A bare name still resolves, but it is ambiguous the moment two agents share it — which is normal in a fleet — so qualify it.

Discovery (read-only — find who to address, then message them over the bus):
  - \`curl -s localhost:${NEXUS_BUS_PORT:-${SLACK_BRIDGE_PORT:-8788}}/agents\` — the live fleet from the KV; each entry carries a ready-to-paste \`fqdn\`
  - \`$REGISTRY_SCRIPT peers --exclude ${MY_PANE_ID}\` — THIS host's agents only (slot, name, directory)
  - \`$REGISTRY_SCRIPT whoami --exclude ${MY_PANE_ID}\` — show your own slot, name, and directory

The transport is NATS. Slack carries only the human notify/reply leg — no agent-to-agent traffic. \`--via-slack\` survives as a deprecated alias of \`--via-bus\`; despite the name it forces the NATS bus.

Fallback — direct local send (same-host only; NOT durable or auditable and can be missed). Prefer the bus; only use this for a local/ephemeral ping, and say that you did:
  - \`$SEND_SCRIPT --local <slot_or_name> <message>\` — inject straight into a same-host agent's pane
  - \`$REGISTRY_SCRIPT broadcast --exclude ${MY_PANE_ID} <message>\` — send to ALL other agents at once"
  else
    comms_body="To message another agent:
  - \`$REGISTRY_SCRIPT peers --exclude ${MY_PANE_ID}\` — list all active agents
  - \`$SEND_SCRIPT <slot_or_name> <message>\` — send a message to a specific agent
  - \`$REGISTRY_SCRIPT broadcast --exclude ${MY_PANE_ID} <message>\` — send to ALL other agents
  - \`$REGISTRY_SCRIPT whoami --exclude ${MY_PANE_ID}\` — show your own slot, name, and directory"
  fi
  registry_section="## Agent Communication
You are agent **${MY_NAME}** on host **${MY_HOST}**. You are part of a multi-agent system; peers may be on THIS host or remote. Peer names are often FQDN-style \`<host>/…/<name>\`: a peer whose name is prefixed \`${MY_HOST}/\` is on the SAME box as you — hand files to it directly by writing into its repo tree under \`~/repos\` (e.g. \`.../docs/incoming\`), NO S3/user-drop detour; only a cross-host handoff needs a transfer mechanism. (Messaging still goes over the bus either way.) ALWAYS pass --exclude ${MY_PANE_ID} to avoid listing yourself.

${comms_body}

### Current Peers
\`\`\`
${peers_output}
\`\`\`
Re-run peers before messaging to get up-to-date slot numbers; prefer name-based addressing over slot numbers."
fi

# ── Query prior knowledge from memory store ────────────────────────────────
memory_section=""
if [ "${NEXUS_INJECT_MEMORY:-1}" = "1" ] && [ "${NEXUS_CONTEXT_MODE:-full}" != "pointer" ] && [ -x "$NEXUS_TMUX_DIR/memory-recall.py" ]; then
  memory_section=$("$MEMORY_PYTHON" "$NEXUS_TMUX_DIR/memory-recall.py" "$project_slug" --max-tokens "${NEXUS_MEMORY_MAX_TOKENS:-2000}" 2>/dev/null || true)
fi

# ── Pointer mode: a lean "load context on demand" note replacing the eager dump ─
# In pointer mode the checkpoint + memory + peers blocks above are skipped entirely
# (no filesystem/DB/registry reads at spawn). Instead the agent gets a short pointer
# telling it HOW to pull each on demand when a task actually needs it. Gated by the
# same INJECT flags so turning a block off also removes its pointer line.
pointer_section=""
if [ "${NEXUS_CONTEXT_MODE:-full}" = "pointer" ]; then
  _pl=""
  if [ "${NEXUS_INJECT_CHECKPOINTS:-1}" = "1" ]; then
    _pl="${_pl}- Recent checkpoints: read the newest \`${CHECKPOINT_SRC}/*-${project_slug}-checkpoint.md\` files (or run your checkpoint skill) for what recent sessions did."$'\n'
  fi
  if [ "${NEXUS_INJECT_MEMORY:-1}" = "1" ]; then
    _pl="${_pl}- Prior knowledge: query the agent-memory MCP (\`search_similar\`/\`query_notes\`, project \`${project_slug}\`) before non-trivial work."$'\n'
  fi
  if [ "${NEXUS_INJECT_REGISTRY:-1}" = "1" ] && [ -x "$REGISTRY_SCRIPT" ]; then
    _pl="${_pl}- Peers / messaging: you are agent **${MY_NAME}** on **${MY_HOST}** in a multi-agent system. Get the live fleet from the NATS presence KV with \`curl -s localhost:${NEXUS_BUS_PORT:-${SLACK_BRIDGE_PORT:-8788}}/agents\` (each entry carries a ready-to-paste \`fqdn\`; \`$REGISTRY_SCRIPT peers --exclude ${MY_PANE_ID}\` lists THIS host only), then message by FQDN with \`$SEND_SCRIPT <host>/<workspace>/<name> <message>\` (NATS bus; durable, cross-host). Add \`--local\` for a same-host pane injection."$'\n'
  fi
  if [ -n "$_pl" ]; then
    pointer_section="## Context (load on demand)
This spawn is lean — recent checkpoints, prior-knowledge notes, and the peer roster were NOT pasted in. Pull only what a task needs:
${_pl}"
  fi
fi

# ── Orchestrator seed / restore (seeded and restored agents) ───────────────
# SEED_PROMPT        — a task to begin on immediately (e.g. the request that
#                      triggered the spawn). Becomes the FIRST section of the opening
#                      prompt; the usual checkpoint/memory/registry context follows
#                      for awareness. Delivered as the launch prompt — never via
#                      send-keys — so there is no terminal-readiness race.
# RESTORE_CHECKPOINT — path to a specific checkpoint file to resume from (a reaped
#                      agent's last checkpoint). Injected as restore context when
#                      readable; logs + falls back to a plain spawn when missing.
# Both are unset for normal launches, so default behavior is unchanged.
seed_section="${SEED_PROMPT:-}"
restore_section=""
if [ -n "${RESTORE_CHECKPOINT:-}" ]; then
  if [ -r "$RESTORE_CHECKPOINT" ]; then
    restore_section="$(cat "$RESTORE_CHECKPOINT")"
  else
    echo "open-claude: RESTORE_CHECKPOINT not readable ($RESTORE_CHECKPOINT) — restoring without it" >&2
  fi
fi

# ── Build claude args ──────────────────────────────────────────────────────
claude_args=()
# CLAUDE_EXTRA_ARGS - verbatim extra flags, word-split on purpose.
#
# For genuinely unattended spawns. CLAUDE_PERMISSION_MODE alone cannot get there,
# because EVERY posture has its own first-run dialog and a spawned pane sits on
# whichever one it hits with nobody to answer:
#   manual            -> "Do you want to proceed?" at the first tool call
#   bypassPermissions -> "you accept all responsibility" consent, persisted
#                        nowhere in ~/.claude.json, so it returns every session
#   auto              -> "Set up auto mode for your environment?" onboarding
# `claude --dangerously-skip-permissions` is the one that comes up running, and
# it is a FLAG not a mode, so it needs a passthrough. Observed on real panes.
#
