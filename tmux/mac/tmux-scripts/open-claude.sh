## Shared working trees — you may not be alone in your checkout

Several repos here have MULTIPLE agents in one working tree, which means **one HEAD and one
working directory between you**. Git will not tell you.

**What actually happened:** one agent checked out `main` while another had work on a branch.
The second saw HEAD on main, zero commits ahead, its files gone from disk, and a smaller test
count — **identical to its work having been destroyed.** Nothing was lost, but only because
the work was already committed.

- **Commit early, to an explicitly named branch (no slashes in branch name).** Necessary,
  and *not sufficient*.
- **Always use an explicit pathspec.** A bare `git commit` sweeps whatever a peer left staged.
  That happened, and cost a `reset --soft` to undo. Verify what you swept by **content hash,
  not filename** — a file can appear in both lists and differ.
- **Re-read `git status` immediately before any branch operation.** What you saw a minute ago
  has moved.
- **If your files appear to have vanished, check `git reflog` BEFORE reporting loss.** It is
  the only thing that distinguishes *destroyed* from *checked-out-elsewhere*.
- **Never `git clean -fd`** in a shared tree — including when the blocking files look
  worthless. The natural fix for *"untracked working tree files would be overwritten by
  merge"* is exactly that command; remove blockers **by explicit path** instead.

**⛔ A NEGATIVE CONTROL NEVER GOES IN A SHARED TREE.** If you are deliberately breaking
something to prove a check can fail — a broken test, a malformed file, a planted secret — do
it in `git worktree add` or a temp clone, **never** by checking it into the shared tree, even
briefly. For the two minutes it is there, any peer running the suite sees a red result that is
not theirs and has no way to know it is yours. This is the rule that branch hygiene does not
cover: committed, well-named branches still hand a peer a broken working directory just for
being present. Deliberate damage needs isolation even more than accidental damage does.

## Reporting conventions (fleet-wide)

**Tag every factual claim with how you know it.** Whenever you state something another
agent or the orchestrator might act on:

- `VERIFIED <file:line>` / `VERIFIED <command>` — you checked it yourself, this session
- `RELAYED` — you are passing on someone else'"'"'s claim, unchecked
- `ASSUMED` — plausible, reasoned from, not checked

**An untagged claim will be read as VERIFIED.** If you did not check it, say so — including
when the claim came from the orchestrator. "My orchestrator told me" is RELAYED, not
VERIFIED, and relaying it untagged is how one wrong claim reaches three agents at once.

**Before acting irreversibly on a RELAYED claim, re-derive it.** Cheaply, once. Applies to
migrations, merges, deletes, prod config, and anything a human can see.

**Derivable values: derive them, never record them.** A commit count, a row count, a file
list — quote the COMMAND, not the number. A recorded derivable is a fact with an expiry date
that nothing announces. If a number must appear, stamp it as a measurement with a time.

**Say what would have made you wrong.** A green check that cannot fail carries no information.
If you report a passing test, a clean sweep, or "no instances found", state what a failure
would have looked like and confirm that outcome was actually reachable.

**Provenance applies to REVIEWS, not just reports — this is where it fails in practice.**
Observed on this fleet: one reviewer named its method ("confirmed via search that X is
defined once") — legibly VERIFIED. A second restated the *author'"'"'s own central measurement*
as its own finding, with no sign it re-ran anything, and approved. That is RELAYED content
wearing a VERIFIED sentence and carrying a signature, so the next reader sees **two sources
agreeing when there is still only one.**

**The reviewer is where a bad number should die. Untagged, it is where the number gets
laundered.** So: tag your review claims, re-run what you repeat, and when auditing a review
panel, grep the review bodies for the author'"'"'s own figures — **a verbatim echo is the tell.**

**Every PR body carries a `VERIFY:` line.** One line, naming a measurement that would come
out DIFFERENT if your change did not work.

It must be something someone else can run. `CI is green`, `tests pass` and `see the diff`
are not measurements — they restate the process, not the outcome. A verifier agent reads
these after merge and reports CONFIRMED, DRIFTED, or UNFALSIFIABLE.

**If you cannot write that line, you have not established your change works** — that is a
finding about the change, not a formatting problem. Say so in the PR rather than inventing
a claim.'
fi

# ── Guard: prove the conventions block survived its own quoting ────────────
# The block above is ONE single-quoted string. An unescaped apostrophe in the
# prose closes it mid-statement, and the assignment then becomes a PREFIX
# assignment on whatever word follows -- so conventions_section ends up EMPTY
# rather than truncated, and the prose up to the next apostrophe EXECUTES as
# shell commands.
#
# An ODD number of stray apostrophes fails loudly at spawn. An EVEN number
# passes `bash -n` and every other syntax check, which is exactly how two of
# them shipped through three commits and silently removed the entire standing
# brief from every spawned agent for three days before anyone noticed.
#
# Escape apostrophes inside the block the way the rest of it does. To launch
# deliberately without a brief, set NEXUS_INJECT_CONVENTIONS=0 -- do not
# delete this check.
CONVENTIONS_MIN_BYTES="${CONVENTIONS_MIN_BYTES:-2000}"
if [ "${NEXUS_INJECT_CONVENTIONS:-1}" = "1" ] && [ "${#conventions_section}" -lt "$CONVENTIONS_MIN_BYTES" ]; then
  printf '%s\n' \
    "open-claude: FATAL - conventions_section is ${#conventions_section} bytes, floor is ${CONVENTIONS_MIN_BYTES} (source: ${conventions_source})." \
    "  Inline block: broken quoting, almost certainly an unescaped apostrophe. File: empty or truncated." \
    "  Agents would otherwise launch with no standing brief and nothing would say so." \
    "  Fix the quoting, or set NEXUS_INJECT_CONVENTIONS=0 to launch without one." >&2
  exit 1
fi

# ── Review partner (set NEXUS_REVIEW_PARTNER=<fqdn> at spawn) ──────────────
# Added 2026-09-07: overnight, every highest-value finding came from agents reviewing
# each other, and all of it was ACCIDENTAL overlap. Pairing formalises that in PARALLEL —
# one central reviewer is a serial bottleneck and lacks the domain context that catches.
pairing_section=""
if [ -n "${NEXUS_REVIEW_PARTNER:-}" ]; then
  pairing_section="## Your review partner: \`${NEXUS_REVIEW_PARTNER}\`

Message them with \`$SEND_SCRIPT ${NEXUS_REVIEW_PARTNER} <one-line message>\`.

**Send them your findings before you act on anything that touches shared code, and
review theirs when they send.** You are not asking permission — the standing
authorization above still applies and you should keep moving. You are getting a second
pair of eyes from someone with overlapping context, which is the thing that has caught
the most real defects in this fleet.

**What a useful review is, based on what actually worked:**

- **Check the claim, not the conclusion.** The catches that mattered were all of the form
  \"that is true of the table but not of the API\", \"that idiom exists but is not present in
  these queries\", \"you checked the container, not the content\".
- **Say which parts you did NOT check.** A review that reads as complete when it was partial
  is worse than no review.
- **Disagree in the open.** Do not soften a correction to be collegial. Two agents that
  agree because neither looked are worth less than one that looked.
- **\"Your usage is correct\" is a claim like any other** — if a peer tells you your code is
  fine, verify it yourself before relying on it. That exact sentence preceded the discovery
  of a live 74-row leak on this fleet.

**PROVISIONAL — this mechanism is under evaluation.** What demonstrably worked was
*independent overlapping context*: agents who already knew the code, arrived at it for their
own reasons, and disagreed. An ASSIGNED partner is not automatically that, and a dutiful
low-context review is the exact failure a single central reviewer would produce. So:

**If you do not have real context on what your partner sent, say so and do not approve.**
"I lack the context to check this" is a useful review. A nod is not. Naming the parts you
could not judge is what keeps a second signature from becoming a second rubber stamp.

Reviewing costs you a few minutes and is the highest-yield thing you will do today."
fi

